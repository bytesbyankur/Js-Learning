// Q. Print numbers 1–10 using:

// for loop

// while loop

// do...while loop


console.log("For Loop")
for (let i=1;i<=10;i++){
    console.log(i)
}

console.log("While Loop")

let i=1
while(i<=10){
    console.log(i)
    i++
}

console.log("Do while Loop")
let j=1
do{
    console.log(j)
    j++
} while(j<=10)